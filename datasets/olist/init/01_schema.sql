-- =====================================================================
-- Olist Brazilian E-Commerce -- OLTP schema for the course labs
-- =====================================================================
-- Mount this folder at /docker-entrypoint-initdb.d of the official
-- postgres image; scripts run once, in file-name order, against the
-- default database (POSTGRES_DB) when the data volume is empty.
--
-- Column names are IDENTICAL to the Kaggle CSVs
-- (https://www.kaggle.com/datasets/olistbr/brazilian-ecommerce), including
-- the original typos "product_name_lenght" / "product_description_lenght".
-- Course additions (not in Kaggle):
--   * updated_at timestamp on every table -> incremental import (L04) & CDC (L08)
--   * orders.order_seq: numeric surrogate key (identity, increases with
--     insertion/purchase time). order_id stays the primary key; order_seq exists
--     so Sqoop --split-by / --incremental append and Spark JDBC partitionColumn
--     have a numeric column to work with (the Olist ids are text hashes).
--   * a trigger that bumps updated_at on every UPDATE
--   * primary keys and ON DELETE CASCADE foreign keys
-- =====================================================================

CREATE TABLE IF NOT EXISTS customers (
    customer_id              varchar(32)  PRIMARY KEY,
    customer_unique_id       varchar(32)  NOT NULL,
    customer_zip_code_prefix integer,
    customer_city            varchar(64),
    customer_state           char(2),
    updated_at               timestamp    NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS sellers (
    seller_id              varchar(32) PRIMARY KEY,
    seller_zip_code_prefix integer,
    seller_city            varchar(64),
    seller_state           char(2),
    updated_at             timestamp   NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS products (
    product_id                 varchar(32) PRIMARY KEY,
    product_category_name      varchar(64),
    product_name_lenght        integer,
    product_description_lenght integer,
    product_photos_qty         integer,
    product_weight_g           integer,
    product_length_cm          integer,
    product_height_cm          integer,
    product_width_cm           integer,
    updated_at                 timestamp   NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS orders (
    order_id                      varchar(32) PRIMARY KEY,
    customer_id                   varchar(32) NOT NULL REFERENCES customers (customer_id) ON DELETE CASCADE,
    order_status                  varchar(16) NOT NULL,
    order_purchase_timestamp      timestamp   NOT NULL,
    order_approved_at             timestamp,
    order_delivered_carrier_date  timestamp,
    order_delivered_customer_date timestamp,
    order_estimated_delivery_date timestamp,
    order_seq                     bigint      GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    updated_at                    timestamp   NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS order_items (
    order_id            varchar(32)   NOT NULL REFERENCES orders (order_id) ON DELETE CASCADE,
    order_item_id       integer       NOT NULL,
    product_id          varchar(32)   NOT NULL REFERENCES products (product_id) ON DELETE CASCADE,
    seller_id           varchar(32)   NOT NULL REFERENCES sellers (seller_id) ON DELETE CASCADE,
    shipping_limit_date timestamp,
    price               numeric(10,2) NOT NULL,
    freight_value       numeric(10,2) NOT NULL,
    updated_at          timestamp     NOT NULL DEFAULT now(),
    PRIMARY KEY (order_id, order_item_id)
);

CREATE TABLE IF NOT EXISTS order_payments (
    order_id             varchar(32)   NOT NULL REFERENCES orders (order_id) ON DELETE CASCADE,
    payment_sequential   integer       NOT NULL,
    payment_type         varchar(16)   NOT NULL,
    payment_installments integer       NOT NULL,
    payment_value        numeric(10,2) NOT NULL,
    updated_at           timestamp     NOT NULL DEFAULT now(),
    PRIMARY KEY (order_id, payment_sequential)
);

-- Indexes that make watermark-based incremental reads cheap
CREATE INDEX IF NOT EXISTS idx_customers_updated_at      ON customers (updated_at);
CREATE INDEX IF NOT EXISTS idx_sellers_updated_at        ON sellers (updated_at);
CREATE INDEX IF NOT EXISTS idx_products_updated_at       ON products (updated_at);
CREATE INDEX IF NOT EXISTS idx_orders_updated_at         ON orders (updated_at);
CREATE INDEX IF NOT EXISTS idx_orders_purchase_ts        ON orders (order_purchase_timestamp);
CREATE INDEX IF NOT EXISTS idx_orders_customer           ON orders (customer_id);
CREATE INDEX IF NOT EXISTS idx_order_items_updated_at    ON order_items (updated_at);
CREATE INDEX IF NOT EXISTS idx_order_payments_updated_at ON order_payments (updated_at);

-- Keep updated_at honest: every UPDATE bumps it (unless the statement sets it explicitly).
CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger AS $$
BEGIN
    IF NEW.updated_at IS NOT DISTINCT FROM OLD.updated_at THEN
        NEW.updated_at := now();
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DO $$
DECLARE t text;
BEGIN
    FOREACH t IN ARRAY ARRAY['customers','sellers','products','orders','order_items','order_payments'] LOOP
        EXECUTE format('DROP TRIGGER IF EXISTS trg_%1$s_updated_at ON %1$I', t);
        EXECUTE format('CREATE TRIGGER trg_%1$s_updated_at BEFORE UPDATE ON %1$I
                        FOR EACH ROW EXECUTE FUNCTION set_updated_at()', t);
    END LOOP;
END;
$$;
